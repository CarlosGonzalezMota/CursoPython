print('*** Operadores comparación (relacionales) ***')

a, b = 7, 5
print(f'Valor inicial: {a}, b: {b}')

# Operador igualdad ==
resultado = a == b # False
print(f'Resultado de a == b: {resultado}')

# Operador diferente !=
resultado = a != b # True
print(f'Resultado de a != b: {resultado}')

# Operador mayor que >
resultado = a > b # True
print(f'Resultado de a > b: {resultado}')

# Operador mayor o igual que >=
resultado = a >= b # True
print(f'Resultado de a >= b: {resultado}')

# Operador menor que
resultado = a < b # False
print(f'Resultado de a < b: {resultado}')

# Operador menor o igual que
resultado = a <= b # False
print(f'Resultado de a <= b: {resultado}')