# Operadores aritméticos

a = 10
b = 3

# Suma +
suma = a + b # Resultado = 13
print(f'Resultado de la suma: {suma}')

# Resta -
resta = a - b # Resultado = 7
print(f'Resultado de la resta: {resta}')

# Multiplicación *
multiplicacion = a * b # Resultado = 30
print(f'Resultado de la multiplicacion: {multiplicacion}')

# División /
division = a / b # Resultado = 3.3333 (Retorna un tipo float)
print(f'Resultado de la division: {division:.2f}')

# División entera //
division_entera = a // b # Resultado = 3
print(f'Resultado de la división entera: {division_entera}')

# Módulo % - Residuo de la división
modulo = a % b # Resultado = 1
print(f'Residuo de la división: {modulo}')

# Exponente ** - Potencia
exponene = a ** b # Resultado = 10^3 (10*10*10)
print(f'Resultado de la exponencial: {exponene}')