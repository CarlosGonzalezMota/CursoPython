print(f'*** El Mayor de 2 Números ***')

# Datos del usuario
primer_numero = int(input('Indique el primer número: '))
segundo_numero = int(input('Indique el segunfo número: '))

# El mayor de dos números
if primer_numero > segundo_numero:
    print(f'El primer número es mayor: {primer_numero}')
else:
    print(f'El segundo número es mayor: {segundo_numero}')