# Programa: Multiplicación de Cadenas

# 1. Crear un separador visual
linea = "=" * 20
print(linea) # Salida: ====================

# 2. Identación simple
nivel = 2
sangria = "    " * nivel
print(sangria + "definicion_bloque_codigo:") # Salida:         definicion_bloque_codigo:

# 3. Patrones simples
print("1" * 5) # 11111 (Texto, no número)

